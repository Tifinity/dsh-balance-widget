#!/usr/bin/env node
/**
 * Inline `src/core.js` into the module-loader client bundle.
 *
 * The Harness browser module table only resolves package ids, not relative
 * files, so the pure logic must be physically present in `client.js`. Keeping
 * the source in `src/` lets `node --test` import it directly.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const corePath = join(root, 'src', 'core.js');
const templatePath = join(root, 'src', 'client.template.js');
const outPath = join(root, 'client.js');

const core = readFileSync(corePath, 'utf8');
const stripped = core.replace(/^export\s+/gm, '');
if (/^\s*(import|export)\s/m.test(stripped)) {
  throw new Error('src/core.js still contains an import/export after stripping');
}
const template = readFileSync(templatePath, 'utf8');
if (!template.includes('/*__CORE__*/')) {
  throw new Error('src/client.template.js is missing the /*__CORE__*/ placeholder');
}

const banner = `// Generated by scripts/build-client.mjs from src/core.js and src/client.template.js.\n// Edit the sources, then run \`npm run build\`.\n`;
const output = banner + template.replace('/*__CORE__*/', () => stripped);
writeFileSync(outPath, output);
console.log(`wrote ${outPath} (${output.length} bytes)`);
